<?php

declare(strict_types=1);

/**
 * Generate the BrickCss lookup tables in assets/brick_css.js from the PHP enums,
 * so the JS decoder and the PHP encoder can never drift. Rewrites only the
 * region between the `<BRICK_CSS_TABLES>` / `</BRICK_CSS_TABLES>` markers.
 *
 *   php bin/gen-css-tables.php
 */

namespace BrickPHP\Style;

spl_autoload_register(static function (string $class): void {
    if (str_starts_with($class, 'BrickPHP\\')) {
        $path = __DIR__ . '/../src/' . str_replace('\\', '/', substr($class, 9)) . '.php';
        if (is_file($path)) {
            require $path;
        }
    }
});

/** JSON with stable, readable formatting for embedding in JS. */
function js(mixed $value): string
{
    return json_encode($value, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
}

// alias code → CSS property name
$prop = [];
foreach (CssProperty::cases() as $p) {
    $prop[$p->alias()] = $p->css();
}

// media / supports token → condition
$media = [];
foreach (CssMedia::cases() as $m) {
    $media[$m->value] = $m->condition();
}
$supports = [];
foreach (CssSupports::cases() as $s) {
    $supports[$s->value] = $s->condition();
}

// combinator token → [before, after] around the selector (derived from wrap())
$combinator = [];
foreach (CssCombinator::cases() as $c) {
    [$before, $after] = explode("\x01", $c->wrap("\x01"));
    $combinator[$c->value] = [$before, $after];
}

// pseudo token → full ':'/'::' selector
$pseudoClass = [];
foreach (CssPseudoClass::cases() as $pc) {
    $pseudoClass[substr($pc->css(), 1)] = $pc->css();
}
$pseudoElement = [];
foreach (CssPseudoElement::cases() as $pe) {
    $pseudoElement[substr($pe->css(), 2)] = $pe->css();
}

// Indent every line after the first, so multi-line JSON bodies align under
// their key inside the generated object literal.
$indent = static fn(string $s): string => implode("\n", array_map(
    static fn(string $line, int $i): string => $i === 0 ? $line : '        ' . $line,
    explode("\n", $s),
    array_keys(explode("\n", $s)),
));

$block = "    // <BRICK_CSS_TABLES> — generated by bin/gen-css-tables.php; do not edit.\n"
    . "    var TABLES = {\n"
    . "        prop: " . $indent(js($prop)) . ",\n"
    . "        media: " . $indent(js($media)) . ",\n"
    . "        supports: " . $indent(js($supports)) . ",\n"
    . "        combinator: " . $indent(js($combinator)) . ",\n"
    . "        pseudoClass: " . $indent(js($pseudoClass)) . ",\n"
    . "        pseudoElement: " . $indent(js($pseudoElement)) . "\n"
    . "    };\n"
    . "    // </BRICK_CSS_TABLES>";

$file = __DIR__ . '/../assets/brick_css.js';
$src = file_get_contents($file);
$pattern = '/[ \t]*\/\/ <BRICK_CSS_TABLES>.*?\/\/ <\/BRICK_CSS_TABLES>/s';
$out = preg_replace($pattern, $block, $src, -1, $count);

if ($count !== 1) {
    fwrite(STDERR, "error: expected exactly one <BRICK_CSS_TABLES> region, found $count\n");
    exit(1);
}

file_put_contents($file, $out);
echo "updated $file — "
    . count($prop) . " props, " . count($media) . " media, " . count($supports) . " supports, "
    . count($combinator) . " combinators, " . count($pseudoClass) . " pseudo-classes, "
    . count($pseudoElement) . " pseudo-elements\n";
