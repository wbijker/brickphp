    // Escape a class name for use in a `.selector` — CSSOM-style: word chars
    // pass through, a leading digit gets a hex escape, everything else is
    // back-slash-escaped. Mirror of CssClass::cssEscape().
    function cssEscape(name) {
        var out = '';
        for (var i = 0; i < name.length; i++) {
            var ch = name[i];
            var code = name.charCodeAt(i);
            if ((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || ch === '_' || code >= 0x80) {
                out += ch;
            } else if (ch >= '0' && ch <= '9') {
                out += i === 0 ? '\\3' + ch + ' ' : ch;
            } else if (ch === '-') {
                out += i === 0 ? '\\-' : '-';
            } else {
                out += '\\' + ch;
            }
        }
        return out;
    }

    // Parse a class name into its parts. Mirror of CssClass::decode().
    function decode(name) {
        var open = name.indexOf('[');
        var close = name.lastIndexOf(']');
        if (open < 0 || close < 0 || close < open) {
            throw new Error('not a BrickCss name (no bracketed value): ' + name);
        }
        var value = name.slice(open + 1, close).split('_').join(' ');

        var head = name.slice(0, open).replace(/-+$/, '');
        var segments = head === '' ? [] : head.split('_');
        var alias = segments.pop();

        var parts = {
            media: [], supports: [], combinators: [], pseudoClasses: [],
            pseudoElement: null,
            propertyName: has(TABLES.prop, alias) ? TABLES.prop[alias] : alias,
            value: value
        };

        for (var i = 0; i < segments.length; i++) {
            var t = segments[i];
            if (has(TABLES.media, t)) parts.media.push(TABLES.media[t]);
            else if (has(TABLES.supports, t)) parts.supports.push(TABLES.supports[t]);
            else if (has(TABLES.combinator, t)) parts.combinators.push(TABLES.combinator[t]);
            else if (has(TABLES.pseudoElement, t)) parts.pseudoElement = TABLES.pseudoElement[t];
            else if (has(TABLES.pseudoClass, t)) parts.pseudoClasses.push(TABLES.pseudoClass[t]);
            else throw new Error("unknown variant token '" + t + "' in: " + name);
        }
        return parts;
    }

    // Reconstruct the full CSS rule for a class name. Mirror of CssClass::cssFor().
    function rule(name) {
        var p = decode(name);

        var sel = '.' + cssEscape(name);
        for (var i = 0; i < p.combinators.length; i++) {
            sel = p.combinators[i][0] + sel + p.combinators[i][1];
        }
        for (var j = 0; j < p.pseudoClasses.length; j++) sel += p.pseudoClasses[j];
        if (p.pseudoElement) sel += p.pseudoElement;

        var out = sel + '{' + p.propertyName + ':' + p.value + '}';
        if (p.supports.length) out = '@supports ' + p.supports.join(' and ') + '{' + out + '}';
        if (p.media.length) out = '@media ' + p.media.join(' and ') + '{' + out + '}';
        return out;
    }

    function has(obj, key) {
        return key != null && Object.prototype.hasOwnProperty.call(obj, key);
    }

    // Does this class name look like a BrickCss utility (alias-[value])?
    function isBrickClass(name) {
        return name.indexOf('-[') >= 0 && name.charAt(name.length - 1) === ']';
    }

    // ---- injection (browser) ----------------------------------------------

    var seen = Object.create(null);
    var sheet = null;

    function stylesheet() {
        if (sheet) return sheet;
        var el = document.createElement('style');
        el.setAttribute('data-brick-css', '');
        document.head.appendChild(el);
        sheet = el.sheet;
        return sheet;
    }

    // Inject the rule for one class name (idempotent). Returns false if the
    // name isn't a BrickCss class or was already injected.
    function ensure(name) {
        if (seen[name] || !isBrickClass(name)) return false;
        seen[name] = true;
        try {
            stylesheet().insertRule(rule(name), stylesheet().cssRules.length);
        } catch (e) {
            if (typeof console !== 'undefined') console.warn('BrickCss: bad class ' + name, e);
            return false;
        }
        return true;
    }

    // Inject every BrickCss class found under `root` (default: document).
    function scan(root) {
        var scope = root || document;
        var nodes = scope.querySelectorAll('[class]');
        for (var i = 0; i < nodes.length; i++) {
            var list = nodes[i].classList;
            for (var j = 0; j < list.length; j++) ensure(list[j]);
        }
    }

    // Watch the document for added nodes / class changes and inject on the fly.
    function observe() {
        scan(document);
        var mo = new MutationObserver(function (records) {
            for (var i = 0; i < records.length; i++) {
                var r = records[i];
                if (r.type === 'attributes' && r.target.classList) {
                    var cl = r.target.classList;
                    for (var k = 0; k < cl.length; k++) ensure(cl[k]);
                } else {
                    for (var j = 0; j < r.addedNodes.length; j++) {
                        var node = r.addedNodes[j];
                        if (node.nodeType === 1) {
                            if (node.classList) {
                                for (var m = 0; m < node.classList.length; m++) ensure(node.classList[m]);
                            }
                            scan(node);
                        }
                    }
                }
            }
        });
        mo.observe(document.documentElement, {
            subtree: true, childList: true, attributes: true, attributeFilter: ['class']
        });
        return mo;
    }

    return {
        decode: decode,
        rule: rule,
        ensure: ensure,
        scan: scan,
        observe: observe,
        isBrickClass: isBrickClass,
        tables: TABLES
    };
